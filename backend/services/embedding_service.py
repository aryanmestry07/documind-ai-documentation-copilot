from sentence_transformers import SentenceTransformer

class EmbeddingServices:
    def __init__(self):
        self.model = SentenceTransformer("all-MiniLM-L6-v2")


    def generate_embeddings(self, texts: list[str]):  # text -> chunks generated by chunk service
        embeddings = self.model.encode(
            texts,
            normalize_embeddings= True, # useful when comparing them usinng cosine similary
            convert_to_numpy=True   # convenient for numerical opreations
        )

        return embeddings